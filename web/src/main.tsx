import { forwardRef } from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter, Link as RouterLink } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { LinkProvider, Toasty, TooltipProvider, type LinkComponentProps } from '@cloudflare/kumo';
import App from './App';
import '@cloudflare/kumo/styles/standalone';
import './tool-theme.css';
import { initializeTheme } from './lib/theme';
import { toastManager } from './lib/toast';
initializeTheme();
const queryClient = new QueryClient({ defaultOptions: { queries: { staleTime: 10_000, refetchOnWindowFocus: false, retry: 1 }, mutations: { retry: 0 } } });
const AppLink = forwardRef<HTMLAnchorElement, LinkComponentProps>(({ href, ...props }, ref) => <RouterLink ref={ref} to={href ?? ''} {...props} />);
AppLink.displayName = 'AppLink';
const root = document.getElementById('root');
if (!root) throw new Error('NewNexus root is missing');
createRoot(root).render(<QueryClientProvider client={queryClient}><TooltipProvider delay={300} closeDelay={0} timeout={500}><Toasty toastManager={toastManager}><BrowserRouter><LinkProvider component={AppLink}><App /></LinkProvider></BrowserRouter></Toasty></TooltipProvider></QueryClientProvider>);
